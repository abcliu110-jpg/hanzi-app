def f(v):
    return ('%.1f' % v).rstrip('0').rstrip('.')


def circle(cx, cy, r, start=-90, ry=None):
    """从 start 角（度）开始画一整圈（两段弧）"""
    ry = ry or r
    a = math.radians(start)
    x0, y0 = cx + r * math.cos(a), cy + ry * math.sin(a)
    x1, y1 = cx - r * math.cos(a), cy - ry * math.sin(a)
    return f'M{f(x0)} {f(y0)} A{f(r)} {f(ry)} 0 1 1 {f(x1)} {f(y1)} A{f(r)} {f(ry)} 0 1 1 {f(x0)} {f(y0)}'


def capsule(b1, b2, tip, r):
    """手指：从 b1 上到指尖、绕过去、回到 b2（不含起点 M）"""
    mx, my = (b1[0] + b2[0]) / 2, (b1[1] + b2[1]) / 2
    ux, uy = tip[0] - mx, tip[1] - my
    L = math.hypot(ux, uy); ux, uy = ux / L, uy / L
    nx, ny = -uy, ux
    p1 = (tip[0] - nx * r, tip[1] - ny * r); p2 = (tip[0] + nx * r, tip[1] + ny * r)
    return f'L{f(p1[0])} {f(p1[1])} A{f(r)} {f(r)} 0 0 1 {f(p2[0])} {f(p2[1])} L{f(b2[0])} {f(b2[1])}'


def leaf(x, y, dx, dy, k=.22):
    mx, my, nx, ny = x + dx / 2, y + dy / 2, -dy * k, dx * k
    return f'M{f(x)} {f(y)} Q{f(mx + nx)} {f(my + ny)} {f(x + dx)} {f(y + dy)} Q{f(mx - nx)} {f(my - ny)} {f(x)} {f(y)}'


def scallop(cx, cy, rx, ry, n, bump=.22, start=200):
    """云朵/树冠：一圈小鼓包"""
    pts = []
    for i in range(n + 1):
        a = math.radians(start + i * 360 / n)
        pts.append((cx + rx * math.cos(a), cy + ry * math.sin(a)))
    s = f'M{f(pts[0][0])} {f(pts[0][1])}'
    for i in range(n):
        a = math.radians(start + (i + .5) * 360 / n)
        q = (cx + rx * (1 + bump) * math.cos(a), cy + ry * (1 + bump) * math.sin(a))
        s += f' Q{f(q[0])} {f(q[1])} {f(pts[i + 1][0])} {f(pts[i + 1][1])}'
    return s


